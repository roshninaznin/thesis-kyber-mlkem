#!/usr/bin/env bash
# make_tables.sh - build thesis-ready Markdown tables from the committed result CSVs.
# Reads only results/*.csv and results/bench/overhead.txt; writes results/TABLES.md.
# Re-run any time; the output is a derived artifact, never edited by hand.
set -u
cd "$HOME/thesis/thesis-artifact" || exit 66
OUT=results/TABLES.md

sym() { case "$1" in FLAGGED) echo F;; "NO ISSUE OBSERVED") echo .;; "BUILD FAIL") echo B;;
  INCONCLUSIVE) echo I;; REVIEW) echo R;; *) echo "?";; esac; }

# grid <csv> <variant-label-in-col1> : opt rows x (compiler,lto) columns of status symbols
grid() {
  awk -F, -v V="$2" '
    $1==V { s=$16; gsub(/ /,"_",s)
      k=$5; c=$3"/"$6; st[k][c]=s; opt[k]=1; col[c]=1 }
    END {
      no=split("Os O2nv O3 O1 O3nv", oo, " ")
      nc=split("clang-18/off clang-18/on clang-21/off clang-21/on gcc-15/off gcc-15/on", cc, " ")
      printf "| opt |"; for(j=1;j<=nc;j++) printf " %s |", cc[j]; printf "\n"
      printf "|---|"; for(j=1;j<=nc;j++) printf "---|"; printf "\n"
      for(i=1;i<=no;i++){ o=oo[i]; if(!(o in opt)) continue
        printf "| %s |", o
        for(j=1;j<=nc;j++){ v=st[o][cc[j]]; gsub(/_/," ",v)
          printf " %s |", (v==""?" ":substr(v,1,1)" ") }
        printf "\n" } }' "$1"
}

{
echo "# Result tables (generated by make_tables.sh from the committed CSVs)"
echo
echo "Legend: **F** = FLAGGED, **N** = NO ISSUE OBSERVED, **B** = BUILD FAIL,"
echo "**I** = INCONCLUSIVE, **R** = REVIEW, blank = not in this experiment."
echo "Columns are compiler/LTO. All cells pass functional tests and the known-answer test."
echo

echo "## Table 1. Kyber reference, pre-registered matrix (results/cells.csv)"
echo; echo "### V0 (vulnerable, b628ba7)"; echo; grid results/cells.csv v0
echo; echo "### V1 (upstream fix, 9b8d306)"; echo; grid results/cells.csv v1
echo

echo "## Table 2. mlkem-native (results/mlkem.csv)"
echo; echo "### V2 (stock v2.0.0)"; echo; grid results/mlkem.csv v2
echo; echo "### V3 (value barriers removed)"; echo; grid results/mlkem.csv v3
echo; echo "Planted-leak control (v2leak), must be FLAGGED:"
awk -F, '$1=="v2leak"{printf "- %s %s lto=%s: %s (%s contexts, %s)\n",$3,$5,$6,$16,$12,$13}' results/mlkem.csv
echo

echo "## Table 3. V0-flags, mitigation flags without changing source (results/flags.csv)"
echo; echo "Placement: compile = -mllvm ...; link = -Wl,-mllvm,...; both = both stages."
echo
echo "| opt | no-LTO compile | LTO compile | LTO link | LTO both |"
echo "|---|---|---|---|---|"
for opt in Os O2nv O3; do
  c=$(awk -F, -v o=$opt '$1=="v0-flags-compile"&&$5==o&&$6=="off"{print $16}' results/flags.csv)
  lc=$(awk -F, -v o=$opt '$1=="v0-flags-compile"&&$5==o&&$6=="on"{print $16}' results/flags.csv)
  ll=$(awk -F, -v o=$opt '$1=="v0-flags-link"&&$5==o&&$6=="on"{print $16}' results/flags.csv)
  lb=$(awk -F, -v o=$opt '$1=="v0-flags-both"&&$5==o&&$6=="on"{print $16}' results/flags.csv)
  echo "| $opt | $c | $lc | $ll | $lb |"
done
echo; echo "Reference: plain V0 at these levels (no flags) is FLAGGED at -Os and -O2nv (matrix)."
echo

echo "## Table 4. Purnal's two extra configurations, no LTO (results/purnal_extra.csv)"
echo; echo "| variant | -O1 clang-18 | -O1 clang-21 | -O1 gcc-15 | -O3nv clang-18 | -O3nv clang-21 | -O3nv gcc-15 |"
echo "|---|---|---|---|---|---|---|"
for v in v0 v1; do
  printf "| %s |" $v
  for opt in O1 O3nv; do for cc in clang-18 clang-21 gcc-15; do
    printf " %s |" "$(awk -F, -v v=$v -v o=$opt -v c=$cc '$1==v&&$5==o&&$3==c&&$6=="off"{print $16}' results/purnal_extra.csv)"
  done; done; printf "\n"
done
echo

echo "## Table 5. dudect timing (max |t|, three repetitions per cell)"
echo; echo "dudect thresholds: |t| > 10 probably not constant time, > 500 definitely not."
echo
echo "| cell | rep 1 | rep 2 | rep 3 | label |"
echo "|---|---|---|---|---|"
for f in results/dudect/dudect.csv results/dudect_extra/dudect_extra.csv; do
  [ -f "$f" ] || continue
  awk -F, 'NR>1{t[$1]=t[$1]" "$5; lab[$1]=$8; if(!seen[$1]++) order[++n]=$1}
    END{for(i=1;i<=n;i++){c=order[i]; split(t[c],a," ")
      printf "| %s |%s|%s|%s| %s |\n", c, (a[1]?" "a[1]" ":"  "), (a[2]?" "a[2]" ":"  "), (a[3]?" "a[3]" ":"  "), lab[c]}}' "$f"
done
echo

echo "## Table 6. Decapsulation performance (results/bench)"
echo; echo "Median cycles over 11 rounds (median of per-run medians), lowest and highest round."
echo
echo "| variant | opt | median | lowest round | highest round |"
echo "|---|---|---|---|---|"
sort -t, -k2,2 -k1,1 results/bench/summary.csv | awk -F, '{printf "| %s | %s | %s | %s | %s |\n",$1,$2,$3,$4,$5}'
echo; echo "Overhead and pre-registered 5% decision (verbatim from results/bench/overhead.txt):"; echo '```'
cat results/bench/overhead.txt; echo '```'
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
